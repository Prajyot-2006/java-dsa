
import java.util.ArrayList;

public class StringArrayList026 {
    public static void main(String[] args) {
        ArrayList<String> s = new ArrayList<>();
        s.add("hello");
        s.add("i");
        s.add("am");
        s.add("prajyot");
        for (String ele : s) {
            System.out.print(ele + " ");
        }
    }
}
